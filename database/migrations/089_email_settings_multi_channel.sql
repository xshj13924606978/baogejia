-- 089_email_settings_multi_channel.sql
-- #[20260828-1345]-1 email_settings 升级为多通道：
--   支持配置多套 SMTP（任意服务商：QQ/163/企业邮/Gmail 等），发送时按 id 升序取首个
--   enabled 且凭据完整的 smtp 通道；无可用 smtp 通道时 fallback 到 Supabase 内置邮件。
--   既有的 id=1 行（provider=supabase）保留为默认记录，不参与 smtp 选择。

-- 移除单行约束（id=1 check）
alter table email_settings drop constraint if exists email_settings_id_check;

-- 改为自增 identity（多行插入）
alter table email_settings alter column id drop default;
alter table email_settings alter column id add generated by default as identity;

-- 修正 identity 序列起始值，避免与既有 id=1 行冲突（新插入从 2 开始）
do $$
declare
  seq_name text;
begin
  select pg_get_serial_sequence('email_settings', 'id') into seq_name;
  if seq_name is not null then
    perform setval(seq_name, greatest((select coalesce(max(id), 1) from email_settings), 1));
  end if;
end $$;

comment on table email_settings is '邮件发送通道配置（多行）。provider=smtp 且 enabled 的行表示自定义 SMTP 通道，按 id 升序取首个凭据完整者；无可用 smtp 行时使用 Supabase 内置邮件通道';
